// The Bash layer of a write-confined specialist (`can_only_write_to = "workdir"`): one Seatbelt profile (the servers' profile text, config/server-sandbox.ts
// `seatbeltProfile`, with the Bash layer's own spec) and the wrapper Claude Code runs every shell command through.
//
// Why hydra's profile and not Claude Code's own sandbox. Claude Code's Bash sandbox allows the keychain's Mach service (`com.apple.SecurityServer`)
// unconditionally, and its `allowMachLookup` setting can only add to the allow list. `security`, git-credential-osxkeychain and every other
// credential helper reach the whole keychain through that service without reading a file, so no file rule stops them: only a Mach-lookup deny
// does. macOS lets a process apply one Seatbelt profile and refuses a second (`sandbox_apply: Operation not permitted`, pinned by a test), so the
// deny cannot be added on top of Claude Code's sandbox: hydra's profile is the layer, and Claude Code's is off (daemon/write-confinement.ts).
//
// What it covers and does not: the shell commands Claude Code runs (the Bash tool, and the hooks it runs through the same shell). Claude Code
// itself, MCP servers and the browser run outside it, so Claude Code keeps its own login, and a server or the browser can still reach the keychain.

import { SANDBOX_EXEC, CLAUDE_CWD_MARKER_REGEX, KEYCHAIN_MACH_DENIES, seatbeltProfile } from './server-sandbox.js'
import type { LoadEnv } from './types.js'

/** The profile lines that deny the keychain (the one list, config/server-sandbox.ts). */
export const BASH_KEYCHAIN_DENIES = KEYCHAIN_MACH_DENIES

/**
 * The profile for a write-confined specialist's Bash: writes only in `writable` (its workdir and the temp folder) and Claude Code's working-directory
 * marker; `cannotRead` (the credential places, hydra's state folder, other specialists' workdirs: `readDenyRoots`) unreadable and unwritable; the keychain's
 * Mach services denied; and what Claude Code's own sandbox denied that the profile text carries (unix sockets but name lookup, other processes'
 * environment and signals, LaunchServices, preferences, the pasteboard, terminal ioctl). The network stays open.
 */
export function bashProfile(env: Pick<LoadEnv, 'realpath'>, spec: { cannotRead: readonly string[]; writable: readonly string[] }): string {
  return seatbeltProfile(env, { roots: spec.cannotRead.map(path => ({ label: 'cannot_read', path })), writable: spec.writable, writableRegex: [CLAUDE_CWD_MARKER_REGEX], keychain: true })
}

const shq = (s: string): string => "'" + s.replace(/'/g, "'\\''") + "'"

/**
 * The script Claude Code runs for every shell command (`CLAUDE_CODE_SHELL_PREFIX`: it is started with the command's text as its one argument, and a hook's
 * command text too). It runs that text, by the shell Claude Code uses, under the profile; nothing is left that runs a command without it. The first time, it
 * proves the profile applies (a probe under it) and leaves the marker the start check waits for: written here, outside the profile, in a place the shell
 * cannot write. A profile that cannot be applied exits 126 with nothing run.
 */
export function bashWrapper(o: { profile: string; marker: string }): string {
  return [
    '#!/bin/bash',
    '# Generated by hydra for a write-confined specialist. Claude Code runs it with each shell command (or hook) text as $1.',
    'sh="${SHELL:-/bin/bash}"',
    'case "$sh" in /*) ;; *) sh=/bin/bash ;; esac',
    `[ -e ${shq(o.marker)} ] || { ${SANDBOX_EXEC} -f ${shq(o.profile)} /usr/bin/true && : > ${shq(o.marker)}; } || exit 126`,
    `exec ${SANDBOX_EXEC} -f ${shq(o.profile)} "$sh" -c "$1"`,
    '',
  ].join('\n')
}
